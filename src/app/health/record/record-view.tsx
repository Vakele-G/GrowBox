"use client";

import Link from "next/link";
import type { Route } from "next";
import { Pill, SectionTitle } from "@/components/ui";
import { BAND_LABELS, type HealthResult } from "@/lib/domain/health";
import type { Business, BusinessMetrics, Transaction } from "@/lib/domain/types";

interface RecordViewProps {
  business: Business;
  metrics: BusinessMetrics;
  health: HealthResult;
  transactions: Transaction[];
  generatedDate: string;
}

export function RecordView({
  business,
  metrics,
  health,
  transactions,
  generatedDate,
}: RecordViewProps) {
  const handlePrint = () => {
    if (typeof window !== "undefined") {
      window.print();
    }
  };

  const handleDownloadCsv = () => {
    if (typeof window === "undefined") return;

    const headers = ["Date", "Type", "Category", "Description", "Amount (ZAR)", "Source", "External Reference"];
    const rows = transactions.map((t) => [
      t.occurredOn,
      t.type,
      t.category,
      `"${t.description.replace(/"/g, '""')}"`,
      (t.amountCents / 100).toFixed(2),
      t.source,
      t.externalId ?? "",
    ]);

    const csvContent = [headers.join(","), ...rows.map((r) => r.join(","))].join("\n");
    const blob = new Blob([csvContent], { type: "text/csv;charset=utf-8;" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.setAttribute("download", `trading-history-${business.name.toLowerCase().replace(/\s+/g, "-")}.csv`);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  };

  const netProfitCents = metrics.totalSalesCents - metrics.totalExpensesCents;
  const periodStart = transactions.length > 0
    ? transactions[transactions.length - 1]?.occurredOn ?? "2026-10-01"
    : "2026-10-01";
  const periodEnd = transactions.length > 0
    ? transactions[0]?.occurredOn ?? generatedDate
    : generatedDate;

  return (
    <div className="space-y-4 pb-12 print:p-0 print:space-y-3">
      {/* Back button and Print buttons (hidden during print) */}
      <div className="flex items-center justify-between print:hidden">
        <Link
          href={"/health" as Route}
          className="text-xs font-bold text-forest hover:underline flex items-center gap-1"
        >
          ← Back to Health Score
        </Link>
        <div className="flex items-center gap-2">
          <button
            onClick={handleDownloadCsv}
            className="btn-secondary px-3 py-1.5 text-xs font-semibold"
          >
            Download CSV
          </button>
          <button
            onClick={handlePrint}
            className="btn-primary px-3 py-1.5 text-xs font-bold"
          >
            Print / Save PDF
          </button>
        </div>
      </div>

      {/* Official Certificate Header */}
      <div className="rounded-2xl border-2 border-line bg-paper p-5 shadow-sm space-y-4">
        <div className="flex items-start justify-between border-b border-line pb-4">
          <div>
            <div className="flex items-center gap-2">
              <span className="text-xs font-extrabold tracking-wider uppercase text-leaf">
                GrowBox Credit-Readiness Story
              </span>
              <Pill tone="amber">Simulated Data</Pill>
            </div>
            <h1 className="text-2xl font-black text-ink mt-1">{business.name}</h1>
            <p className="text-xs text-muted">
              {business.municipality} · Registered Stage: {business.stage.toUpperCase()}
            </p>
          </div>
          <div className="text-right">
            <p className="text-[10px] text-muted uppercase font-bold">Report Date</p>
            <p className="text-xs font-semibold text-ink">{generatedDate}</p>
            <p className="text-[10px] text-muted mt-1">Period: {periodStart} to {periodEnd}</p>
          </div>
        </div>

        {/* Disclaimer */}
        <div className="rounded-lg bg-sand/60 border border-line p-3 text-[11px] text-muted leading-relaxed">
          <strong>Notice to Credit Assessors:</strong> Simulated demo data. This record is generated by GrowBox from the transactions recorded in the application and is not a formal bank statement. Lenders and partners must verify the underlying bank statements and source transactions.
        </div>

        {/* Health Score Summary Banner */}
        <div className="flex items-center justify-between rounded-xl bg-forest/5 p-4 border border-forest/20">
          <div>
            <p className="text-xs text-forest font-bold uppercase tracking-wider">
              Business Health Score
            </p>
            <div className="flex items-baseline gap-2 mt-0.5">
              <span className="text-3xl font-black text-ink">{health.score}</span>
              <span className="text-xs text-muted font-semibold">/ 100</span>
            </div>
          </div>
          <div className="text-right">
            <Pill tone={health.score >= 60 ? "green" : "amber"}>
              {BAND_LABELS[health.band]} Band
            </Pill>
            <p className="text-[10px] text-muted mt-1">
              Deterministic 6-pillar score
            </p>
          </div>
        </div>

        {/* Financial Track Record Grid */}
        <div className="grid grid-cols-2 sm:grid-cols-3 gap-3">
          <div className="rounded-xl border border-line p-3 bg-sand/30">
            <p className="text-[10px] uppercase font-bold text-muted">Trading Days (30d)</p>
            <p className="text-lg font-bold text-ink mt-0.5">
              {metrics.tradingDaysLast30} days
            </p>
            <p className="text-[10px] text-forest font-medium">
              {metrics.loggedDaysLast30} logged days
            </p>
          </div>

          <div className="rounded-xl border border-line p-3 bg-sand/30">
            <p className="text-[10px] uppercase font-bold text-muted">Total Sales</p>
            <p className="text-lg font-bold text-forest mt-0.5">
              R{(metrics.totalSalesCents / 100).toFixed(2)}
            </p>
            <p className="text-[10px] text-muted">
              4-wk: R{(metrics.fourWeekSalesCents / 100).toFixed(0)}
            </p>
          </div>

          <div className="rounded-xl border border-line p-3 bg-sand/30">
            <p className="text-[10px] uppercase font-bold text-muted">Total Expenses</p>
            <p className="text-lg font-bold text-amber-800 mt-0.5">
              R{(metrics.totalExpensesCents / 100).toFixed(2)}
            </p>
            <p className="text-[10px] text-muted">
              4-wk: R{(metrics.fourWeekExpensesCents / 100).toFixed(0)}
            </p>
          </div>

          <div className="rounded-xl border border-line p-3 bg-sand/30">
            <p className="text-[10px] uppercase font-bold text-muted">Net Operating Profit</p>
            <p className="text-lg font-bold text-forest mt-0.5">
              R{(netProfitCents / 100).toFixed(2)}
            </p>
            <p className="text-[10px] text-muted">All-time retained</p>
          </div>

          <div className="rounded-xl border border-line p-3 bg-sand/30">
            <p className="text-[10px] uppercase font-bold text-muted">Average Gross Margin</p>
            <p className="text-lg font-bold text-ink mt-0.5">
              {metrics.fourWeekMarginPct.toFixed(1)}%
            </p>
            <p className="text-[10px] text-muted">4-week average</p>
          </div>

          <div className="rounded-xl border border-line p-3 bg-sand/30">
            <p className="text-[10px] uppercase font-bold text-muted">Cash Buffer / Runway</p>
            <p className="text-lg font-bold text-ink mt-0.5">
              {metrics.savingsBufferWeeks.toFixed(1)} wks
            </p>
            <p className="text-[10px] text-muted">
              {metrics.cashRunwayDays ? `${metrics.cashRunwayDays} days runway` : "Healthy"}
            </p>
          </div>
        </div>

        {/* Health Score Pillar Breakdown */}
        <div className="space-y-2 pt-2 border-t border-line">
          <SectionTitle title="Health Score Component Breakdown" />
          <div className="grid grid-cols-2 gap-2 text-xs">
            <div className="rounded-lg border border-line p-2">
              <span className="text-muted block text-[10px]">Profitability (max 25)</span>
              <span className="font-bold text-ink">{health.components.profitability} / 25 pts</span>
            </div>
            <div className="rounded-lg border border-line p-2">
              <span className="text-muted block text-[10px]">Cash Buffer (max 20)</span>
              <span className="font-bold text-ink">{health.components.cashBuffer} / 20 pts</span>
            </div>
            <div className="rounded-lg border border-line p-2">
              <span className="text-muted block text-[10px]">Record Consistency (max 20)</span>
              <span className="font-bold text-ink">{health.components.recordConsistency} / 20 pts</span>
            </div>
            <div className="rounded-lg border border-line p-2">
              <span className="text-muted block text-[10px]">Margin Stability (max 15)</span>
              <span className="font-bold text-ink">{health.components.marginStability} / 15 pts</span>
            </div>
            <div className="rounded-lg border border-line p-2">
              <span className="text-muted block text-[10px]">Savings Discipline (max 10)</span>
              <span className="font-bold text-ink">{health.components.savingsDiscipline} / 10 pts</span>
            </div>
            <div className="rounded-lg border border-line p-2">
              <span className="text-muted block text-[10px]">Compliance Progress (max 10)</span>
              <span className="font-bold text-ink">{health.components.complianceProgress} / 10 pts</span>
            </div>
          </div>
        </div>

        {/* Transaction History Ledger */}
        <div className="space-y-2 pt-2 border-t border-line">
          <div className="flex items-center justify-between">
            <SectionTitle title="Trading History Ledger" />
            <span className="text-[10px] text-muted">
              Showing latest {Math.min(transactions.length, 25)} of {transactions.length} entries
            </span>
          </div>

          <div className="overflow-x-auto">
            <table className="w-full text-left text-xs border border-line">
              <thead className="bg-sand/60 text-ink text-[10px] uppercase font-bold border-b border-line">
                <tr>
                  <th className="p-2">Date</th>
                  <th className="p-2">Description</th>
                  <th className="p-2">Source</th>
                  <th className="p-2">Category</th>
                  <th className="p-2 text-right">Amount</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-line">
                {transactions.slice(0, 25).map((t) => (
                  <tr key={t.id} className="hover:bg-sand/20">
                    <td className="p-2 font-mono text-[10px]">{t.occurredOn}</td>
                    <td className="p-2 font-medium text-ink">
                      {t.description}
                      {t.externalId && (
                        <span className="text-[9px] text-muted block font-mono">
                          Ref: {t.externalId}
                        </span>
                      )}
                    </td>
                    <td className="p-2">
                      <span className="text-[9px] uppercase px-1.5 py-0.5 rounded bg-sand font-bold text-muted">
                        {t.source}
                      </span>
                    </td>
                    <td className="p-2 text-muted">{t.category}</td>
                    <td
                      className={`p-2 text-right font-bold ${
                        t.type === "sale" ? "text-forest" : "text-amber-800"
                      }`}
                    >
                      {t.type === "sale" ? "+" : "-"}R{(t.amountCents / 100).toFixed(2)}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </div>
      </div>
    </div>
  );
}
